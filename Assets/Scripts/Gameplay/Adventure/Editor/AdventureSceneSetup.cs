using System;
using System.Linq;
using Poker.SingleBattle;
using TMPro;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.InputSystem.UI;
using UnityEngine.SceneManagement;

namespace Poker.Adventure.Editor
{
    public static class AdventureSceneSetup
    {
        public const string ScenePath = "Assets/Scenes/SingleChapterAdventure.unity";
        public const string BattleContentPath = "Packages/com.kaya.battle-engine/Content/SingleChapterBattle.xml";
        public const string AdventureContentPath = "Packages/com.kaya.battle-engine/Content/SingleChapterAdventure.xml";

        [MenuItem("工具/局外冒险/创建单章七站场景")]
        public static void Create()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("请先退出播放模式。");
            if (AssetDatabase.LoadAssetAtPath<SceneAsset>(ScenePath) != null)
                throw new InvalidOperationException("单章场景已存在；请直接打开，避免覆盖场景调整。");
            var battle = AssetDatabase.LoadAssetAtPath<TextAsset>(BattleContentPath);
            var adventure = AssetDatabase.LoadAssetAtPath<TextAsset>(AdventureContentPath);
            var font = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>("Assets/Fonts/NotoSansCJK/TMP/NotoSansCJKSCRegular.asset");
            if (battle == null || adventure == null || font == null) throw new InvalidOperationException("单章 XML 或中文字体缺失。");
            if (!AssetDatabase.CopyAsset("Assets/Scenes/BattleDemo.unity", ScenePath)) throw new InvalidOperationException("无法复制战斗场景。");
            var previous = SceneManager.GetActiveScene();
            var scene = EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Additive);
            try
            {
                SceneManager.SetActiveScene(scene);
                var roots = scene.GetRootGameObjects();
                var view = roots.SelectMany(r => r.GetComponentsInChildren<SingleBattleSceneAdapter>(true)).Single();
                var gameplay = roots.Single(r => r.name == "Gameplay");
                var hide = roots.Where(r => r == gameplay || r.name == "Battle Hand Backdrop").ToArray();
                // Input must remain alive while the battle's UI and hand are hidden.
                var input = roots.SelectMany(r => r.GetComponentsInChildren<EventSystem>(true)).FirstOrDefault();
                if (input == null)
                {
                    var inputRoot = new GameObject("Adventure Input", typeof(EventSystem), typeof(InputSystemUIInputModule));
                    input = inputRoot.GetComponent<EventSystem>();
                    inputRoot.GetComponent<InputSystemUIInputModule>().AssignDefaultActions();
                }
                input.transform.SetParent(null, true); input.gameObject.SetActive(true);
                view.ConfigureContent(battle, "single-chapter-battle-1");
                view.SceneHost.Configure(view, view, false, true);
                var host = new GameObject("Adventure Run").AddComponent<AdventureSceneHost>();
                host.Configure(battle, adventure, view, hide);
                var layout = host.gameObject.AddComponent<AdventureBattleLayout>();
                layout.Configure(host, roots.SelectMany(r => r.GetComponentsInChildren<BattleBackgroundSwitcher>(true)).FirstOrDefault());
                layout.ConfigureArtwork(AssetDatabase.LoadAssetAtPath<Material>(AdventureArtworkSetup.MinionMaterialPath),
                    AssetDatabase.LoadAssetAtPath<Material>(AdventureArtworkSetup.EliteMaterialPath),
                    AssetDatabase.LoadAssetAtPath<Material>("Assets/Art/Characters/BattleBillboards/Enemy.mat"));
                var screen = new GameObject("Adventure UI", typeof(RectTransform)).AddComponent<AdventureScreen>();
                screen.Configure(host, font);
                // Screen widgets are generated by AdventureScreen at runtime.
                foreach (var root in hide) root.SetActive(false);
                EditorSceneManager.MarkSceneDirty(scene);
                if (!EditorSceneManager.SaveScene(scene)) throw new InvalidOperationException("无法保存单章场景。");
                var builds = EditorBuildSettings.scenes.ToList();
                if (!builds.Any(s => s.path == ScenePath))
                { builds.Add(new EditorBuildSettingsScene(ScenePath, true)); EditorBuildSettings.scenes = builds.ToArray(); }
                Debug.Log("单章七站场景已创建：" + ScenePath);
            }
            finally
            {
                if (previous.IsValid() && previous.isLoaded) SceneManager.SetActiveScene(previous);
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        [MenuItem("工具/局外冒险/打开单章七站场景")]
        public static void Open()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("请先退出播放模式。");
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
            EditorSceneManager.OpenScene(ScenePath);
        }

        [MenuItem("工具/局外冒险/配置整局敌人布局")]
        public static void ConfigureLayout()
        {
            var scene = SceneManager.GetActiveScene();
            if (Application.isPlaying || scene.path != ScenePath) throw new InvalidOperationException("请在编辑模式打开单章场景。");
            var roots = scene.GetRootGameObjects();
            var host = roots.SelectMany(r => r.GetComponentsInChildren<AdventureSceneHost>(true)).Single();
            var layout = host.GetComponent<AdventureBattleLayout>();
            if (layout == null) layout = host.gameObject.AddComponent<AdventureBattleLayout>();
            layout.Configure(host, roots.SelectMany(r => r.GetComponentsInChildren<BattleBackgroundSwitcher>(true)).FirstOrDefault());
            EditorSceneManager.MarkSceneDirty(scene); EditorSceneManager.SaveScene(scene);
        }
    }
}
